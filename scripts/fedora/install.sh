#!/usr/bin/env bash
# Install VectorCraft natively on Fedora (and other dnf-based distros).
#
# Installs the system packages needed to build VectorCraft's dependencies,
# creates an isolated virtual environment and installs VectorCraft into it.
# Nothing is installed into the system Python, so dnf-managed packages are
# never touched.
#
# Usage:
#   scripts/fedora/install.sh [options]
#
# Options:
#   --venv DIR        Virtual environment location
#                     (default: ~/.local/share/vectorcraft/venv)
#   --python BIN      Python interpreter to use (default: python3)
#   --with "PKGS"     Extra pip packages to install alongside VectorCraft,
#                     e.g. --with "faiss-cpu beautifulsoup4"
#   --editable        Install the checkout in editable (development) mode
#   --no-system-deps  Skip the dnf step (e.g. no sudo access)
#   --force           Run even if the OS is not detected as Fedora
#   -h, --help        Show this help

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
VENV_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/vectorcraft/venv"
PYTHON_BIN="python3"
EXTRA_PKGS=""
EDITABLE=0
SYSTEM_DEPS=1
FORCE=0

usage() { sed -n '2,/^$/p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --venv) VENV_DIR="$2"; shift 2 ;;
    --python) PYTHON_BIN="$2"; shift 2 ;;
    --with) EXTRA_PKGS="$2"; shift 2 ;;
    --editable) EDITABLE=1; shift ;;
    --no-system-deps) SYSTEM_DEPS=0; shift ;;
    --force) FORCE=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

log() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }

# --- OS detection -----------------------------------------------------------
if [[ -r /etc/os-release ]]; then
  # shellcheck disable=SC1091
  . /etc/os-release
fi
if [[ "${ID:-}" != "fedora" && " ${ID_LIKE:-} " != *" fedora "* ]]; then
  if [[ $FORCE -eq 0 ]]; then
    echo "This installer targets Fedora (detected: ${PRETTY_NAME:-unknown})." >&2
    echo "Re-run with --force to continue anyway." >&2
    exit 1
  fi
  log "Non-Fedora system detected (${PRETTY_NAME:-unknown}); continuing because of --force"
else
  log "Detected ${PRETTY_NAME:-Fedora}"
fi

# --- System packages --------------------------------------------------------
# python3-devel + gcc/gcc-c++ let pip build any dependency that has no
# prebuilt wheel for Fedora's Python version.
DNF_PKGS=(python3 python3-pip python3-devel gcc gcc-c++ git)

if [[ $SYSTEM_DEPS -eq 1 ]]; then
  if ! command -v dnf >/dev/null 2>&1; then
    echo "dnf not found; install these packages manually: ${DNF_PKGS[*]}" >&2
    echo "or re-run with --no-system-deps." >&2
    exit 1
  fi
  SUDO=""
  if [[ $EUID -ne 0 ]]; then
    SUDO="sudo"
  fi
  log "Installing system packages: ${DNF_PKGS[*]}"
  $SUDO dnf install -y "${DNF_PKGS[@]}"
fi

# --- Virtual environment ----------------------------------------------------
if ! command -v "$PYTHON_BIN" >/dev/null 2>&1; then
  echo "Python interpreter '$PYTHON_BIN' not found." >&2
  exit 1
fi

if ! "$PYTHON_BIN" -c 'import sys; sys.exit(sys.version_info < (3, 9))'; then
  echo "VectorCraft on Fedora requires Python 3.9 or newer." >&2
  exit 1
fi

log "Creating virtual environment in $VENV_DIR"
mkdir -p "$(dirname "$VENV_DIR")"
"$PYTHON_BIN" -m venv "$VENV_DIR"
VENV_PY="$VENV_DIR/bin/python"

"$VENV_PY" -m pip install --upgrade pip wheel

# --- VectorCraft ------------------------------------------------------------
if [[ $EDITABLE -eq 1 ]]; then
  log "Installing VectorCraft from $REPO_DIR (editable)"
  "$VENV_PY" -m pip install -e "$REPO_DIR"
else
  log "Installing VectorCraft from $REPO_DIR"
  "$VENV_PY" -m pip install "$REPO_DIR"
fi

if [[ -n "$EXTRA_PKGS" ]]; then
  log "Installing extra packages: $EXTRA_PKGS"
  # shellcheck disable=SC2086
  "$VENV_PY" -m pip install $EXTRA_PKGS
fi

# --- Launcher ---------------------------------------------------------------
BIN_DIR="$HOME/.local/bin"
mkdir -p "$BIN_DIR"
LAUNCHER="$BIN_DIR/vectorcraft-python"
cat > "$LAUNCHER" <<LAUNCH
#!/usr/bin/env bash
# Run Python with VectorCraft available (generated by scripts/fedora/install.sh)
exec "$VENV_PY" "\$@"
LAUNCH
chmod +x "$LAUNCHER"

log "Verifying installation"
"$VENV_PY" -c 'import numpy, vectorcraft; print("vectorcraft OK (numpy " + numpy.__version__ + ")")'

cat <<DONE

VectorCraft is installed.

  Activate the environment:   source "$VENV_DIR/bin/activate"
  Or run scripts directly:    vectorcraft-python your_script.py

If 'vectorcraft-python' is not found, make sure ~/.local/bin is on your PATH
(it is by default on Fedora).
DONE
